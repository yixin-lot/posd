// 构建期默认语言：国内发行版 zh-CN，国际版 en-US（打包时用 VITE_DEFAULT_LOCALE 注入）
const BUILD_DEFAULT = (import.meta.env && import.meta.env.VITE_DEFAULT_LOCALE) || 'zh-CN'
const saved = (typeof localStorage !== 'undefined' && localStorage.getItem('pos.locale')) || ''
export const locale = ref(saved || BUILD_DEFAULT)
export const currency = ref(BUILD_DEFAULT === 'zh-CN' ? 'CNY' : 'USD')
export const locales = [
  { id: 'en-US', label: 'English' },
  { id: 'zh-CN', label: '中文' }
]

export function setLocale(id) {
  locale.value = DICT[id] ? id : 'en-US'
  try { localStorage.setItem('pos.locale', locale.value) } catch {}
  if (typeof document !== 'undefined') document.documentElement.lang = locale.value
}

export function t(key, vars = {}) {
  const table = DICT[locale.value] || DICT['en-US']
  let s = table[key] || DICT['en-US'][key] || key
  for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v))
  return s
}

export function setCurrency(code) {
  if (/^[A-Z]{3}$/.test(String(code || ''))) currency.value = code
}

// 金额：内部是元（数字），按 locale + currency 展示
export function money(value, code) {
  const n = Number(value) || 0
  const cur = code || currency.value
  try {
    return new Intl.NumberFormat(locale.value, { style: 'currency', currency: cur }).format(n)
  } catch {
    return n.toFixed(2)
  }
}

// 日期：存储是 ISO 8601，展示跟随 locale
export function dateTime(iso, opts) {
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return ''
  try {
    return new Intl.DateTimeFormat(locale.value, opts || { dateStyle: 'medium', timeStyle: 'short' }).format(d)
  } catch { return iso }
}

export const isZh = computed(() => locale.value === 'zh-CN')
